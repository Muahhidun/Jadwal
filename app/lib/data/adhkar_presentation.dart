/// Отображение утверждённого контента: исходные строки таблицы не меняются,
/// чтобы сохранить происхождение перевода и заметки для религиозной проверки.
String readerSource(String source) => source
    .split(' · ')
    .where((part) => !part.startsWith('аль-Альбани:'))
    .where((part) => !part.contains('«Сахих ат-Таргиб»'))
    .join(' · ');

/// Имя переводчика убрано только из карточки по решению владельца.
/// Это не разрешение на анонимное распространение перевода: права и условия
/// атрибуции остаются отдельной обязательной проверкой до публикации.
String readerTranslation(String text) => text
    .replaceAll('; перевод Э. Кулиева', '')
    .replaceAll('Перевод смыслов Э. Кулиева. ', '');

/// Владелец задал образец 01.10.2026. Меняется кириллическая запись,
/// не арабский текст. Остальные правила (долгота, эмфатические согласные)
/// не угадываем: нужен утверждённый пословный вариант.
String readerTranscription(String text) {
  const oldMorning =
      "Асбахна ва асбахаль-мульку ли-Лляхи, валь-хамду ли-Лляхи, ля иляха илля-Ллаху вахдаху ля шарика лях, ляхуль-мульку ва ляхуль-хамду ва хува 'аля кулли шайин кадир.";
  const oldEvening =
      'Амсайна ва амсаль-мульку ли-Лляхи, валь-хамду ли-Лляхи, ля иляха илля-Ллаху вахдаху ля шарика лях, ляхуль-мульку ва ляхуль-хамду ва хува ‘аля кулли шайин кадир.';
  const formula =
      "лильлях, уаль-хамду лильлях, ля иляха илля Аллах, уахдаху ля шарика лях. Ляхуль-мульку, уа ляхуль-хамду, уа хуа 'аля кулли шайн кодир.";
  var result = text
      .replaceAll(oldMorning, 'Асбахна уа асбахаль-мульку $formula')
      .replaceAll(oldEvening, 'Амсайна уа амсаль-мульку $formula');
  // Кириллическое «в» в этих арабских транскрипциях обозначает و.
  // После «у» не дублируем звук: Хува → Хуа, куфуван → куфуан.
  result = result
      .replaceAll('ув', 'у')
      .replaceAll('Ув', 'У')
      .replaceAll('в', 'у')
      .replaceAll('В', 'У');
  const spellings = {
    'Рабб': 'Робб',
    'рабб': 'робб',
    'Рахман': 'Рохман',
    'рахман': 'рохман',
    'Рахим': 'Рохим',
    'рахим': 'рохим',
    'рахмат': 'рохмат',
    'Радыту': 'Родыту',
    'расулю': 'росулю',
    'Самад': 'Сомад',
    'кадир': 'кодир',
  };
  for (final entry in spellings.entries) {
    result = result.replaceAll(entry.key, entry.value);
  }
  return result;
}
